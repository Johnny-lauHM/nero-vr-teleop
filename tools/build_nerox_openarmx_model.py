#!/usr/bin/env python3
"""Adapt the accepted dual-NERO + TacClaw assembly for OpenArmX.

The source model already expresses joint values in the live NERO encoder
coordinate convention. This adapter changes names only: physical arm_b is
OpenArmX left, physical arm_a is OpenArmX right, and the two reviewed TacClaw
TCP frames receive the names hard-coded by ``PinocchioTeleopCore``.
"""

from __future__ import annotations

import argparse
import copy
import xml.etree.ElementTree as ET
from pathlib import Path


ARM_NAME_MAP = {
    # OpenArmX left/right follow the operator's controllers.
    "arm_b": "openarmx_left",
    "arm_a": "openarmx_right",
}
TCP_NAME_MAP = {
    "openarmx_left_tcp_link": "openarmx_left_link7_pico",
    "openarmx_right_tcp_link": "openarmx_right_link7_pico",
    "openarmx_left_tcp_joint": "openarmx_left_link7_pico_joint",
    "openarmx_right_tcp_joint": "openarmx_right_link7_pico_joint",
}


def _openarmx_name(name: str) -> str:
    if name == "lab_world":
        return "world"
    result = name
    for source_prefix, target_prefix in ARM_NAME_MAP.items():
        if result.startswith(source_prefix):
            result = target_prefix + result[len(source_prefix) :]
            break
    return TCP_NAME_MAP.get(result, result)


def _required_names() -> tuple[set[str], set[str]]:
    joints = {
        f"openarmx_{side}_joint{index}"
        for side in ("left", "right")
        for index in range(1, 8)
    }
    links = {
        f"openarmx_{side}_link7_pico" for side in ("left", "right")
    }
    return joints, links


def build_model(source: Path, output: Path) -> None:
    source_root = ET.parse(source).getroot()
    robot = ET.Element("robot", {"name": "nerox_openarmx_bimanual"})
    robot.append(
        ET.Comment(
            " Generated by name-only adaptation of models/source/"
            "nero_dual_tacclaw.urdf; NERO hardware zero remains q=0. "
        )
    )

    for source_element in source_root:
        if source_element.tag not in ("link", "joint"):
            continue
        element = copy.deepcopy(source_element)
        name = element.get("name")
        if not name:
            raise ValueError(f"{element.tag} without name in {source}")
        element.set("name", _openarmx_name(name))

        if element.tag == "link":
            # OpenArmX needs kinematics and inertials, not render/collision
            # meshes. Stripping these also removes the package:// dependency
            # from the standalone teleoperation model.
            for tag in ("visual", "collision"):
                for child in list(element.findall(tag)):
                    element.remove(child)
        else:
            parent = element.find("parent")
            child = element.find("child")
            if parent is None or child is None:
                raise ValueError(f"joint lacks parent/child: {name}")
            parent_name = parent.get("link")
            child_name = child.get("link")
            if not parent_name or not child_name:
                raise ValueError(f"joint has empty parent/child: {name}")
            parent.set("link", _openarmx_name(parent_name))
            child.set("link", _openarmx_name(child_name))
        robot.append(element)

    actual_joints = {
        str(element.get("name")) for element in robot.findall("joint")
    }
    actual_links = {
        str(element.get("name")) for element in robot.findall("link")
    }
    required_joints, required_links = _required_names()
    if missing := sorted(required_joints - actual_joints):
        raise ValueError(f"source model lacks required arm joints: {missing}")
    if missing := sorted(required_links - actual_links):
        raise ValueError(f"source model lacks required TCP links: {missing}")

    ET.indent(robot, space="  ")
    output.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(robot).write(output, encoding="utf-8", xml_declaration=True)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--source",
        type=Path,
        default=root / "models/source/nero_dual_tacclaw.urdf",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=root / "models/nerox_openarmx_bimanual.urdf",
    )
    args = parser.parse_args()
    build_model(args.source.resolve(), args.output.resolve())
    print(args.output.resolve())


if __name__ == "__main__":
    main()
